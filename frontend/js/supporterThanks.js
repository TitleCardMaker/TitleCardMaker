  var messages = [
    'Supported by {name}',
    'Made possible by {name}',
    'Special thanks to {name}',
    '♥ to {name}'
  ];

  function escapeHtml(text) {
    var div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
  }

  var FADE_DURATION_MS = 400;

  function setContent(el) {
    var all = supporters.map(function(n) { return { name: n, super: false }; })
      .concat(superSupporters.map(function(n) { return { name: n, super: true }; }));
    if (all.length === 0) return;
    var msg = messages[Math.floor(Math.random() * messages.length)];
    var supporter = all[Math.floor(Math.random() * all.length)];
    var nameClass = supporter.super ? 'supporter-name supporter-name-super' : 'supporter-name';
    var textClass = supporter.super ? 'supporter-text-super' : 'ui red text';
    var highlightedName = '<strong class="' + nameClass + '"><span class="' + textClass + '">' + escapeHtml(supporter.name) + '</span></strong>';
    el.innerHTML = msg.replace('{name}', highlightedName);
  }

  function updateSupporterThanks(skipFade) {
    var el = document.getElementById('supporter-thanks');
    if (!el) return;
    if (skipFade) {
      setContent(el);
      return;
    }
    el.classList.add('supporter-thanks-fade-out');
    setTimeout(function() {
      setContent(el);
      el.classList.remove('supporter-thanks-fade-out');
    }, FADE_DURATION_MS);
  }

  function init() {
    updateSupporterThanks(true);
    setInterval(function() { updateSupporterThanks(false); }, 15000);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
